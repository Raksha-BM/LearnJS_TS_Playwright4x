/** Arithmetic operators Perform mathematical calculations
 * [ +, -, *, /, %, ** ]
**/

let a = 10;
let b = 3;
console.log(a + b);  // 13
console.log(a - b);  // 7
console.log(a * b);  // 30
console.log(a / b);  // 3.33
console.log(a % b);  // 1
console.log(a ** b); // 1000
console.log( 2 ** 3);  // 2 to the power 3 = 8