// The increment operator increases a variable's value by 1.
let a = 5;
let result = a++; //a++ → use first, increment afterward.

console.log(result); // 5
console.log(a);      // 6

let b = 5;
let result1 = ++b; // ++b → increment first, use afterward.

console.log(result1); // 6
console.log(b);      // 6